def test_saved_answers_replay_a_document_without_any_call(tmp_path, monkeypatch) -> None:
    monkeypatch.setenv("AZURE_OPENAI_ENDPOINT", "https://example.invalid")
    monkeypatch.setenv("AZURE_OPENAI_MODEL", "terra-test")
    monkeypatch.setenv("AZURE_OPENAI_API_KEY", "not-a-real-key")
    data = pdf_bytes(tmp_path, seed=5)
    saved = AnswerCache(tmp_path / "saved-answers")
    azure = RecordingGateway(saved)
    # A first session is allowed live calls: both Azure stages ask the (recording) gateway once.
    live = TestClient(create_app(DeskSettings(work_dir=tmp_path / "live", live=True), allowed_hosts=("testserver",),
                                 live_gateway=lambda connection: azure))
    with live:
        assert live.get("/api/setup").json()["mode"]["live"] is True
        first = stages(run(live, add(live, data)["key"]))
    assert [request.stage for request in azure.requests] == ["read", "inspect"]
    assert (first["read"]["source"], first["inspect"]["source"]) == ("live", "live")
    assert first["read"]["facts"]["read"] and first["read"]["facts"]["fields"] == 1
    assert "01/02/2026" not in json.dumps(first)  # the value read never reaches the page's facts
    # A second session has those answers saved, read only, and no live call: it replays them by their key.
    replay = TestClient(create_app(DeskSettings(work_dir=tmp_path / "replay", saved_answers=(saved.folder,)),
                                   allowed_hosts=("testserver",), live_gateway=lambda connection: pytest.fail("live call")))
    before = sorted(path.name for path in saved.folder.iterdir())
    with replay:
        state = run(replay, add(replay, data)["key"])
    second = stages(state)
    assert (second["read"]["source"], second["inspect"]["source"]) == ("saved", "saved")
    assert state["result"]["skipped"] == [] and len(azure.requests) == 2
    assert sorted(path.name for path in saved.folder.iterdir()) == before  # the saved answers are only read
    answered = {row["kind"] for row in state["result"]["checks"] if row["outcome"] != "not_applicable"}
    assert answered == {"file", "values", "picture"}  # the checks on the reading and on the inspection now answer


def test_a_file_of_the_known_set_gets_its_nature_and_its_saved_reading(tmp_path, monkeypatch) -> None:
    monkeypatch.setenv("CHECK_FALLBACK_FONTS", STAND_IN_FALLBACK)
    data = pdf_bytes(tmp_path, seed=9)
    fingerprint = hashlib.sha256(data).hexdigest()
    team = tmp_path / "team-cache"
    (team / "DOC-777").mkdir(parents=True)
    index = IngestIndex(updated_at=datetime.now(UTC), documents_dir="data/documents", catalogue=None, documents=[
        IndexEntry(id="DOC-777", record="cache/DOC-777/record.json", source_file="data/documents/DOC-777.pdf",
                   fingerprint=fingerprint, kind="pdf_text", family="releve", nature=RELEVE, pages=1)])
    (team / "index.json").write_text(index.model_dump_json(), encoding="utf-8")
    # The batch run's reading of that very file, made with a prompt edited since: its key is no longer found.
    reading = Reading(id="DOC-777", status="read", answer=reading_answer(), model="another-deployment",
                      prompt_version="older", fingerprint=fingerprint)
    (team / "DOC-777" / "reading.json").write_text(reading.model_dump_json(), encoding="utf-8")
    known = find_known(team / "index.json", fingerprint)
    assert known.id == "DOC-777" and known.nature == RELEVE and known.models["read"] == "another-deployment"
    assert find_known(team / "index.json", "0" * 64) is None and find_known(tmp_path / "missing.json", fingerprint) is None
    settings = DeskSettings(work_dir=tmp_path / "work", known_index=team / "index.json")
    with TestClient(create_app(settings, allowed_hosts=("testserver",))) as client:
        document = add(client, data, name="scan.pdf")
        assert document["known"] and document["suggested_nature"] == RELEVE and document["doc_id"] == "DOC-777"
        report = stages(run(client, document["key"]))
        other = stages(run(client, document["key"], nature="Relevé d'identité bancaire"))
    assert (report["read"]["status"], report["read"]["source"]) == ("done", "saved_result")
    assert (report["inspect"]["status"], report["inspect"]["note"]) == ("skipped", "no_saved_answer")
    # given another nature than the batch run's, the file is not read from a reading made for the first one
    assert (other["read"]["status"], other["read"]["note"]) == ("skipped", "no_saved_answer")
    assert json.loads((team / "DOC-777" / "reading.json").read_text(encoding="utf-8"))["id"] == "DOC-777"  # left as it was


def test_the_session_works_outside_the_repository_and_leaves_nothing_behind(tmp_path, monkeypatch) -> None:
    import os
    import tempfile

    from fraudcheck.demo.desk import STALE_AFTER_S, WORK_PREFIX

    temporary = tmp_path / "system-temp"
    killed, alive = temporary / f"{WORK_PREFIX}killed", temporary / f"{WORK_PREFIX}alive"
    for folder in (killed, alive):
        (folder / "documents").mkdir(parents=True)
    long_ago = time.time() - STALE_AFTER_S - 60
    os.utime(killed, (long_ago, long_ago))
    monkeypatch.setattr(tempfile, "tempdir", str(temporary))
    settings = DeskSettings.from_repository()
    assert settings.work_dir.parent == temporary.resolve() and not settings.work_dir.is_relative_to(REPO_ROOT)
    assert settings.saved_answers[0].is_relative_to(REPO_ROOT) and not settings.live  # the team's answers: read only
    assert alive.is_dir() and not killed.exists()  # what a killed session left is removed by the next one
    desk = Desk(DeskSettings(work_dir=tmp_path / "work"))
    document, duplicate = desk.add("DOC-1.pdf", pdf_bytes(tmp_path, seed=2))
    assert not duplicate and document.workspace.file.is_file() and document.workspace.folder.parent == tmp_path / "work"
    desk.close()
    assert not (tmp_path / "work").exists()


def test_the_page_loads_nothing_from_another_site() -> None:
    page = (STATIC / "index.html").read_text(encoding="utf-8")
    style = (STATIC / "app.css").read_text(encoding="utf-8")
    script = (STATIC / "app.js").read_text(encoding="utf-8")
    assert 'lang="fr"' in page and "/static/app.css" in page and "/static/app.js" in page
    for name, text in (("index.html", page), ("app.css", style), ("app.js", script)):
        elsewhere = [url for url in re.findall(r"(?:https?:)?//[\w.-]+\.\w+[^\s\"')]*", text) if "www.w3.org" not in url]
        assert elsewhere == [], (name, elsewhere)
    fonts = re.findall(r'url\("(fonts/[^"]+)"\)', style)
    assert len(fonts) >= 5 and all((STATIC / font).is_file() for font in fonts)
    assert (STATIC / "fonts" / "LICENSE-IBM-Plex.txt").is_file()
    assert "prefers-reduced-motion" in style and "prefers-reduced-motion" in script
    assert "innerHTML" not in script  # results are put on the page as text, never as HTML


