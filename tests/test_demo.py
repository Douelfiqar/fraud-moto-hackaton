def test_refused_files_and_unknown_documents_answer_in_plain_words(client, tmp_path) -> None:
    for data in (b"plain text, not a document", b""):
        refused = client.post("/api/documents", content=data, headers=UPLOAD)
        assert refused.status_code == 400 and refused.json()["detail"]
    assert client.post("/api/documents", content=b"%PDF-1.7", headers={"Content-Type": "text/plain"}).status_code == 415
    too_heavy = client.post("/api/documents", content=b"x", headers={**UPLOAD, "Content-Length": str(MAX_UPLOAD_BYTES + 1)})
    assert too_heavy.status_code == 413
    assert client.get("/api/documents/unknown").status_code == 404
    assert client.get("/api/documents/unknown/pages/1").status_code == 404
