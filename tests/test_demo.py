    first = add(client, data, name="a.pdf")
    same = client.post("/api/documents", content=data, headers={**UPLOAD, "X-File-Name": "b.pdf"}).json()  # the same file again
    assert same["duplicate"] and same["key"] == first["key"] and len(client.get("/api/documents").json()) == 1
    assert client.delete(f"/api/documents/{first['key']}").status_code == 204 and client.get("/api/documents").json() == []
    assert sniff_format(picture_bytes()) == "png" and sniff_format(b"\xff\xd8\xff\xe0") == "jpeg" and sniff_format(b"GIF89a") is None
    assert document_id("scan_doc 707 (1).pdf") == "DOC-707" and document_id("../../etc/passwd") == "document"


