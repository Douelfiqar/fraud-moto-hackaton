def add(client: TestClient, data: bytes, name: str = "DOC-202.pdf") -> dict:
    response = client.post("/api/documents", content=data, headers={**UPLOAD, "X-File-Name": quote(name)})  # as the page sends it
    assert response.status_code == 201, response.text
    return response.json()


def run(client: TestClient, key: str, nature: str = RELEVE, seconds: float = 120) -> dict:
    """Start the control of a document and wait for its end."""
    assert client.post(f"/api/documents/{key}/analysis", json={"nature": nature}).status_code == 200
    deadline = time.monotonic() + seconds
    while time.monotonic() < deadline:
        state = client.get(f"/api/documents/{key}").json()
        if state["status"] in ("done", "failed"):
            return state
        time.sleep(0.05)
    raise AssertionError("the control did not end in time")


def stages(state: dict) -> dict[str, dict]:
    return {stage["key"]: stage for stage in state["stages"]}


class RecordingGateway:
    """Stands for Azure: fills the form the request names and keeps the answer, as the real gateway does."""

    def __init__(self, cache: AnswerCache) -> None:
        self.cache, self.requests = cache, []

    def ask(self, request) -> GatewayAnswer:
        self.requests.append(request)
        form = reading_answer() if request.schema is ReadingAnswer else inspection_answer()
        answer = GatewayAnswer("read", form, calls=1)
        self.cache.put(request, answer)
        return answer


