def test_a_flagged_document_goes_through_every_stage_and_is_explained(client, tmp_path) -> None:
    document = add(client, pdf_bytes(tmp_path, odd_line=12))
    assert (document["doc_id"], document["format"], document["pages"], document["status"]) == ("DOC-202", "pdf", 1, "uploaded")
    assert not document["known"] and document["suggested_nature"] is None
    state = run(client, document["key"])
    assert state["status"] == "done" and state["nature"] == RELEVE
    report = stages(state)
    assert list(report) == ["prepare", "read", "inspect", "check", "decide"]
    assert report["prepare"]["status"] == "done" and report["prepare"]["facts"]["kind"] == "pdf_text"
    # no saved answer and no live call: the two Azure stages say so, and the local checks still run
    assert [(report[key]["status"], report[key]["note"]) for key in ("read", "inspect")] == [("skipped", "no_saved_answer")] * 2
    assert report["check"]["facts"]["total"] == len(registered()) and report["check"]["facts"]["fail"] == 1
    result = state["result"]
    decision = result["decision"]
    assert decision["flagged"] and decision["line"] == "trusted_check_failed" and decision["confidence"] == 0.9
    assert STAND_IN_FALLBACK in decision["justification"] and decision["clues"] and decision["fraud_type"]
    assert result["skipped"] == ["read", "inspect"]
    rows = {row["name"]: row for row in result["checks"]}
    assert set(rows) == set(registered())
    assert rows["font"] == {"name": "font", "kind": "file", "outcome": "fail", "trusted": True,
                            "evidence": decision["justification"]}
    assert rows["rib_key"]["outcome"] == "not_applicable" and result["counts"]["fail"] == 1
    assert "details" not in json.dumps(state)  # machine-readable facts may hold values of the document


def test_the_handlers_decision_replaces_the_tools_and_is_listed_in_the_journal(client, tmp_path) -> None:
    key = add(client, pdf_bytes(tmp_path, odd_line=12))["key"]
    assert client.post(f"/api/documents/{key}/decision", json={"fake": False}).status_code == 400  # not controlled yet
    run(client, key)
    refused = client.post(f"/api/documents/{key}/decision", json={"fake": True, "reason": "   "})
    assert refused.status_code == 400 and "motif" in refused.json()["detail"]
    corrected = client.post(f"/api/documents/{key}/decision", json={"fake": False}).json()
    assert corrected["review"]["agrees"] is False and not corrected["review"]["fake"]
    assert corrected["final"] == {**corrected["final"], "flagged": False, "line": "reviewed", "reviewed": True}
    assert corrected["result"]["decision"]["flagged"]  # the tool's own opinion stays on record
    confirmed = client.post(f"/api/documents/{key}/decision",
                            json={"fake": True, "reason": "Police différente\nsur une ligne.", "generated": True}).json()
    assert confirmed["review"] == {**confirmed["review"], "fake": True, "agrees": True, "generated": True,
                                   "reason": "Police différente sur une ligne."}
    assert confirmed["final"]["flagged"] and confirmed["final"]["justification"].startswith("Police différente sur une ligne.")
    journal = client.get("/api/journal.csv")
    assert journal.headers["content-type"].startswith("text/csv")
    lines = journal.text.lstrip("﻿").splitlines()
    assert lines[0].startswith("fichier;identifiant;type;verdict_outil") and len(lines) == 2
    assert lines[1].startswith(f"DOC-202.pdf;DOC-202;{RELEVE};signalé;0,90;faux;confirme;Police différente sur une ligne.;oui;")
    reopened = client.delete(f"/api/documents/{key}/decision").json()
    assert reopened["review"] is None and reopened["final"] is None
    assert len(client.get("/api/journal.csv").text.splitlines()) == 1


