def pdf_bytes(tmp_path: Path, odd_line: int | None = None, seed: int = 1) -> bytes:
    """A generated one-page text PDF; ``odd_line`` is set in the stand-in fallback font."""
    path = tmp_path / f"generated-{odd_line}-{seed}.pdf"
    text_pdf(path, odd_line=odd_line, seed=seed)
    return path.read_bytes()


